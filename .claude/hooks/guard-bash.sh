#!/bin/bash
# PreToolUse hook for Bash commands.
# Blocks unsafe or policy-breaking commands before they run.
# Exit 2 blocks the command and sends the reason to Claude.
# Written for macOS bash 3.2, so it avoids newer bash features.

input=$(cat)
cmd=$(printf '%s' "$input" | jq -r '.tool_input.command // empty')

if [ -z "$cmd" ]; then
  exit 0
fi

lower=$(printf '%s' "$cmd" | tr '[:upper:]' '[:lower:]')

block() {
  echo "Blocked by project guardrail: $1" >&2
  exit 2
}

ask() {
  jq -n --arg reason "$1" '{
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "ask",
      permissionDecisionReason: $reason
    }
  }'
  exit 0
}

# No pushing to main or master, and no force pushes.
if printf '%s' "$lower" | grep -Eq 'git([[:space:]]+-[^[:space:]]+)*[[:space:]]+push'; then
  if printf '%s' "$lower" | grep -Eq '(^|[[:space:]])(-f|--force|--force-with-lease)([[:space:]=]|$)'; then
    block "force push is not allowed."
  fi
  if printf '%s' "$lower" | grep -Eq '(^|[[:space:]:/])(main|master)([[:space:]]|$)'; then
    block "pushing to main or master is not allowed. Push the feature branch and open a pull request."
  fi
fi

# Only the director merges, approves or closes pull requests.
if printf '%s' "$lower" | grep -Eq 'gh[[:space:]]+pr[[:space:]]+(merge|review|close)'; then
  block "only the director merges, approves or closes pull requests."
fi

# No AI credit lines in commits.
if printf '%s' "$lower" | grep -Eq 'git([[:space:]]+-[^[:space:]]+)*[[:space:]]+commit'; then
  if printf '%s' "$lower" | grep -Eq 'co-authored-by|generated with|generated by (claude|an ai|ai)|noreply@anthropic\.com'; then
    block "commit messages must not contain AI credit lines (Co-Authored-By, Generated with, and similar)."
  fi
fi

# No skipping quality gates.
if printf '%s' "$cmd" | grep -Eq '(mvnw|mvn)[^|;&]*-D[A-Za-z0-9_.-]*([Ss]kip)'; then
  block "skipping tests or checks with -D...skip flags is not allowed. Run the full gates."
fi

# No reading or printing secrets.
if printf '%s' "$cmd" | grep -Eq '(^|[[:space:]/"'"'"'])\.env(\.local|\.production|\.development)?([[:space:]"'"'"';|&]|$)'; then
  block ".env files may contain secrets and must not be read or printed."
fi
if printf '%s' "$lower" | grep -Eq '(^|[[:space:]])(printenv|env)([[:space:]]*$|[[:space:]]*\|)'; then
  block "printing the whole environment can expose secrets."
fi

# No piping downloads into a shell.
if printf '%s' "$lower" | grep -Eq '(curl|wget)[^|]*\|[[:space:]]*(sudo[[:space:]]+)?(ba|z)?sh'; then
  block "piping a download into a shell is not allowed."
fi

# Destructive commands need the director's confirmation.
# Every path given to a recursive rm must be inside target/, build/ or tmp/.
recursive_rm=$(printf '%s' "$lower" | grep -Eo '(^|[;&|[:space:]])rm[[:space:]]+(-[a-z]*r[a-z]*|--recursive)([[:space:]]+-[a-z]+)*[^;&|]*')
if [ -n "$recursive_rm" ]; then
  unsafe=$(printf '%s\n' "$recursive_rm" \
    | sed -E 's/^[;&|[:space:]]*rm[[:space:]]+//' \
    | tr ' ' '\n' \
    | grep -Ev '^$|^-' \
    | grep -Ev '^(\./)?(target|build|tmp)(/.*)?$')
  if [ -n "$unsafe" ]; then
    ask "recursive delete outside target/, build/ or tmp/. Confirm this is intended."
  fi
fi
if printf '%s' "$lower" | grep -Eq 'git[[:space:]]+(reset[[:space:]]+--hard|clean[[:space:]]+-[a-z]*f)'; then
  ask "this discards local work. Confirm this is intended."
fi
if printf '%s' "$lower" | grep -Eq 'docker[[:space:]]+compose[[:space:]]+down[^|;&]*(-v|--volumes)'; then
  ask "this deletes the local database volume. Confirm this is intended."
fi

exit 0
